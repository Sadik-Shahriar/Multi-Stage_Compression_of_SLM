"""## 11. Statistical analysis, sensitivity, and Pareto uncertainty"""

def read_bool(series):
    if series.dtype == bool:
        return series
    normalized = series.astype(str).str.lower()
    assert normalized.isin(["true", "false"]).all(), sorted(normalized.unique())
    return normalized == "true"

def holm_adjust(p_values):
    p_values = np.asarray(p_values, dtype=float)
    order = np.argsort(p_values)
    ranked = np.minimum(1.0, p_values[order] * (len(p_values) - np.arange(len(p_values))))
    ranked = np.maximum.accumulate(ranked)
    adjusted = np.empty(len(p_values))
    adjusted[order] = ranked
    return adjusted

def paired_test(frame, left, right, metric):
    pair = frame[frame.variant.isin([left, right])].pivot(
        index="block", columns="variant", values=metric,
    )[[left, right]].dropna()
    assert len(pair) == MEASURED_BLOCKS
    diff = pair[left] - pair[right]
    sd = float(diff.std(ddof=1))
    # Mean differences are the estimand; paired t-tests and t intervals are prespecified.
    statistic, p_value = stats.ttest_rel(pair[left], pair[right])
    effect = float(diff.mean() / sd) if sd else np.nan
    sem = stats.sem(diff)
    half = float(stats.t.ppf(0.975, len(diff) - 1) * sem) if sem else 0.0
    return {
        "comparison": f"{left}-{right}", "metric": metric,
        "n": len(diff), "test": "paired_t",
        "mean_difference_j": float(diff.mean()),
        "ci95_low_j": float(diff.mean() - half), "ci95_high_j": float(diff.mean() + half),
        "statistic": float(statistic), "p_unadjusted": float(p_value),
        "paired_d": effect,
    }

def validate_power_traces(frame):
    for row in frame.itertuples(index=False):
        path = Path(row.trace_file)
        assert path.exists(), path
        trace = json.loads(path.read_text())
        energies = []
        for phase in ["prefill", "decode"]:
            samples = trace[phase]
            times = np.asarray([x["elapsed_s"] for x in samples], dtype=float)
            powers = np.asarray([x["power_w"] for x in samples], dtype=float)
            assert len(times) >= 2 and np.all(np.diff(times) >= 0)
            if len(times) > 2:
                assert np.median(np.diff(times)) <= 0.25
            energies.append(float(np.trapezoid(powers, times)))
        assert np.isclose(sum(energies), row.total_energy_j, rtol=1e-9, atol=1e-6)

