class GPUMonitor:
    # Thread-safe 10 Hz sampling with synchronized, ordered endpoints.
    def __init__(self, interval_s=0.1):
        self.interval_s = float(interval_s)
        self.samples = []
        self.running = False
        self.stop_event = threading.Event()
        self.lock = threading.Lock()

    def sample(self, elapsed_s=None):
        row = sensor_sample()
        row["elapsed_s"] = float(
            time.perf_counter() - self.t0 if elapsed_s is None else elapsed_s
        )
        with self.lock:
            self.samples.append(row)

    def poll(self):
        deadline = self.t0 + self.interval_s
        while not self.stop_event.wait(max(0.0, deadline - time.perf_counter())):
            try:
                self.sample()
            except pynvml.NVMLError:
                pass
            deadline += self.interval_s

    def start(self):
        if self.running:
            raise RuntimeError("Monitor is already running.")
        torch.cuda.synchronize()
        self.samples = []
        self.stop_event.clear()
        self.t0 = time.perf_counter()
        self.sample(elapsed_s=0.0)
        self.running = True
        self.thread = threading.Thread(target=self.poll, daemon=True)
        self.thread.start()

    def stop(self):
        if not self.running:
            raise RuntimeError("Monitor is not running.")
        torch.cuda.synchronize()
        self.stop_event.set()
        self.thread.join(timeout=2)
        if self.thread.is_alive():
            raise RuntimeError("Power monitor thread did not terminate.")
        self.sample()
        self.running = False
        with self.lock:
            samples = sorted(self.samples, key=lambda row: row["elapsed_s"])
        if len(samples) < 2:
            raise RuntimeError(f"Only {len(samples)} power samples were captured.")
        t = np.asarray([x["elapsed_s"] for x in samples], dtype=float)
        p = np.asarray([x["power_w"] for x in samples], dtype=float)
        duration = float(t[-1] - t[0])
        assert duration > 0 and np.all(np.diff(t) >= 0) and np.isfinite(p).all()
        energy = float(np.trapezoid(p, t))
        temperatures = [x["temperature_c"] for x in samples if np.isfinite(x["temperature_c"])]
        return {
            "energy_j": energy, "duration_s": duration,
            "avg_power_w": energy / duration, "max_power_w": float(p.max()),
            "nvml_peak_mb": float(max(x["nvml_used_mb"] for x in samples)),
            "max_temperature_c": float(max(temperatures)) if temperatures else np.nan,
            "n_samples": len(samples), "samples": samples,
        }

def measure_idle_telemetry(label, seconds=10.0):
    torch.cuda.synchronize()
    samples, deadline = [], time.perf_counter() + seconds
    while True:
        samples.append(sensor_sample())
        if time.perf_counter() >= deadline:
            break
        time.sleep(0.1)
    powers = np.asarray([x["power_w"] for x in samples])
    temperatures = np.asarray([x["temperature_c"] for x in samples])
    temperatures = temperatures[np.isfinite(temperatures)]
    return {
        "label": label, "seconds": seconds, "samples": len(samples),
        "power_median_w": float(np.median(powers)),
        "power_mean_w": float(powers.mean()), "power_sd_w": float(powers.std(ddof=1)),
        "temperature_median_c": float(np.median(temperatures)) if len(temperatures) else np.nan,
    }

