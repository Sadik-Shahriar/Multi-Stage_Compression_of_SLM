def run_distortion_study(samples):
    rows = []
    for bits in [2, 3, 4]:
        quantizer = TurboQuantMSE(dim=HEAD_DIM, bits=bits, device=str(samples["key"].device))
        for tensor_name in ["key", "value"]:
            original = samples[tensor_name]
            indices, norms = quantizer.quantize(original)
            restored = quantizer.dequantize(indices, norms)
            error = restored.float() - original.float()
            nmse = error.square().sum(-1) / original.float().square().sum(-1).clamp_min(1e-12)
            cosine = F.cosine_similarity(original.float(), restored.float(), dim=-1)
            assert indices.dtype == torch.uint8 and int(indices.max().item()) < 2**bits
            assert torch.isfinite(nmse).all() and torch.isfinite(cosine).all()
            rows.append({
                "fingerprint": EXPERIMENT_FINGERPRINT, "bits": bits,
                "tensor": tensor_name, "vectors": len(original),
                "normalized_mse": float(nmse.mean()),
                "mean_cosine": float(cosine.mean()),
                "physical_index_bytes_per_coordinate": indices.element_size(),
            })
    result = pd.DataFrame(rows)
    result.to_csv(DISTORTION_CSV, index=False)
    return result

