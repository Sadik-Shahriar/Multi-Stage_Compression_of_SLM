def cache_lengths(cache):
    lengths = []
    for layer in cache.layers:
        if hasattr(layer, "_total_len"):
            lengths.append(int(layer._total_len))
        else:
            lengths.append(int(layer.get_seq_length()))
    return lengths

def tensor_storage_bytes(tensors):
    seen, total = set(), 0
    for tensor in tensors:
        if not isinstance(tensor, torch.Tensor) or tensor.numel() == 0:
            continue
        storage = tensor.untyped_storage()
        key = (str(tensor.device), int(storage.data_ptr()), int(storage.nbytes()))
        if key not in seen:
            seen.add(key)
            total += int(storage.nbytes())
    return total

def cache_storage_metrics(cache, prefix):
    all_tensors, indices, payload, materialized = [], [], [], []
    payload_names = {
        "_key_indices", "_value_indices", "_key_norms", "_value_norms",
        "_residual_keys", "_residual_values",
    }
    for layer in cache.layers:
        for name, value in vars(layer).items():
            if isinstance(value, torch.Tensor):
                all_tensors.append(value)
                if name in {"_key_indices", "_value_indices"}:
                    indices.append(value)
                if name in payload_names:
                    payload.append(value)
                if name in {"keys", "values"}:
                    materialized.append(value)
    lengths = cache_lengths(cache)
    retained_fp16 = sum(lengths) * NUM_KV_HEADS * HEAD_DIM * 2 * 2
    live = tensor_storage_bytes(all_tensors)
    package_bytes = 0
    if callable(getattr(cache, "memory_usage_bytes", None)):
        package_bytes = int(cache.memory_usage_bytes().get("total_bytes", 0))
    return {
        f"{prefix}_cache_live_bytes": live,
        f"{prefix}_retained_fp16_bytes": int(retained_fp16),
        f"{prefix}_retained_fp16_to_live_ratio": retained_fp16 / max(live, 1),
        f"{prefix}_tq_index_bytes": tensor_storage_bytes(indices),
        f"{prefix}_tq_payload_bytes": tensor_storage_bytes(payload),
        f"{prefix}_tq_materialized_bytes": tensor_storage_bytes(materialized),
        f"{prefix}_tq_package_reported_bytes": package_bytes,
    }

def validate_cache_path(
    cache, config, ctx, prefill_lengths, decode_tokens,
    average_budget=DEFAULT_AVERAGE_BUDGET, tq_bits=DEFAULT_TQ_BITS,
):
    use_pkv, use_tq = CONFIGS[config]
    assert len(cache.layers) == NUM_LAYERS and len(prefill_lengths) == NUM_LAYERS
    if use_pkv:
        budgets = build_pyramid_budgets(average_budget=average_budget)
        expected = [min(ctx, budget) for budget in budgets]
        evicted = [i for i, budget in enumerate(budgets) if ctx > budget]
        assert prefill_lengths == expected
        assert sorted(row["layer"] for row in PKV_LOG) == evicted
        assert all(
            row["before"] == ctx and row["after"] == expected[row["layer"]]
            and row["budget"] == budgets[row["layer"]] for row in PKV_LOG
        )
    else:
        expected, evicted = [ctx] * NUM_LAYERS, []
        assert prefill_lengths == expected and not PKV_LOG
    final_lengths = cache_lengths(cache)
    assert final_lengths == [length + decode_tokens for length in expected]
    quantized_layers = 0
    if use_tq:
        assert isinstance(cache, TurboQuantCache) and cache.bits == tq_bits
        for layer, total_len in zip(cache.layers, final_lengths):
            assert layer.bits == tq_bits
            quantized_tokens = max(total_len - layer.residual_len, 0)
            residual_tokens = min(total_len, layer.residual_len)
            expected_index_shape = (1, NUM_KV_HEADS, quantized_tokens, HEAD_DIM)
            expected_norm_shape = (1, NUM_KV_HEADS, quantized_tokens, 1)
            if quantized_tokens:
                assert tuple(layer._key_indices.shape) == expected_index_shape
                assert tuple(layer._value_indices.shape) == expected_index_shape
                assert tuple(layer._key_norms.shape) == expected_norm_shape
                assert tuple(layer._value_norms.shape) == expected_norm_shape
            else:
                assert layer._key_indices.numel() == layer._value_indices.numel() == 0
                assert layer._key_norms.numel() == layer._value_norms.numel() == 0
            assert layer._residual_keys.shape[-2] == residual_tokens
            assert layer._residual_values.shape[-2] == residual_tokens
            assert layer.keys.shape[-2] == total_len and layer.values.shape[-2] == total_len
            layer_indices = [layer._key_indices, layer._value_indices]
            present = [x for x in layer_indices if isinstance(x, torch.Tensor) and x.numel()]
            if present:
                quantized_layers += 1
                assert all(x.dtype == torch.uint8 and int(x.max()) < 2**tq_bits for x in present)
        assert quantized_layers == sum(length > 128 for length in final_lengths)
    else:
        assert not isinstance(cache, TurboQuantCache)
    return {
        "structural_pass": True, "quantized_layers": quantized_layers,
        "evicted_layers": len(evicted),
        "cache_min_prefill": min(prefill_lengths), "cache_max_prefill": max(prefill_lengths),
        "cache_min_after": min(final_lengths), "cache_max_after": max(final_lengths),
    }

