def score_niah_response(response, answer):
    normalized = response.strip().casefold()
    normalized_answer = answer.casefold()
    retrieval = re.search(
        rf"(?<![a-z0-9]){re.escape(normalized_answer)}(?![a-z0-9])", normalized,
    ) is not None
    exact_format = response.strip() == answer
    assert not exact_format or retrieval
    return retrieval, exact_format

