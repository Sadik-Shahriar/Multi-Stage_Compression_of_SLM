def completed_keys(path, columns, fingerprint):
    if not path.exists():
        return set()
    old = pd.read_csv(path)
    missing = {"fingerprint", *columns} - set(old.columns)
    if missing:
        raise RuntimeError(f"{path} is missing columns: {sorted(missing)}")
    if "fingerprint" not in old or not (old["fingerprint"] == fingerprint).all():
        raise RuntimeError(f"{path} belongs to a different experiment. Move or delete it.")
    return set(map(tuple, old[columns].itertuples(index=False, name=None)))

def discard_incomplete_blocks(path, variants):
    if not path.exists():
        return
    frame = pd.read_csv(path)
    subset = frame[frame["variant"].isin(variants)]
    incomplete = []
    expected = set(variants)
    for (context, block), group in subset.groupby(["context", "block"]):
        if set(group.variant) != expected or group.session_id.nunique() != 1:
            incomplete.append((context, block))
    if not incomplete:
        return
    remove = pd.Series(False, index=frame.index)
    for context, block in incomplete:
        remove |= (
            frame.variant.isin(variants) & (frame.context == context) & (frame.block == block)
        )
    print("Discarding incomplete cross-session blocks:", incomplete)
    temporary = path.with_suffix(path.suffix + ".tmp")
    frame[~remove].to_csv(temporary, index=False)
    os.replace(temporary, path)

